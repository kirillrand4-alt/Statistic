"""Вектор из 13 свойств шаблона заказчика — одинаково для нашего каталога и для сайтов.

Шаблон («Параметры для списков») задаёт ровно 13 колонок и правило сцепки: точное
совпадение, допусков нет. Десять колонок выделены зелёным — это «свойства, которые
могут не указываться на сайтах», и для них действует правило умолчания: не указано →
первое значение столбца. Три колонки (кВт, бар, степень защиты) зелёным НЕ выделены,
поэтому правило умолчания на них не распространяется:

  * кВт и бар публикуют все площадки — это обязательная часть ключа;
  * IP публикуют не все (Hansmann — ни одной карточки из 133, Xeleron — ни одной).
    Подставлять сюда IP23 «по умолчанию» нельзя: наш BS-5,5BFR-250 — IP55, и тогда
    весь Hansmann отвалился бы, хотя в образце отчёта заказчик сам сцепил его с
    RSA 5.5-8/10-500DR. Поэтому IP — тристейт: неизвестно = совместимо с любым.

Значения возвращаются либо реальные, либо None («на сайте не указано»). Подстановку
умолчаний делает уже матчер — ему нужно видеть разницу между «нет» и «не сказано»,
чтобы посчитать, сколько сцепок держится на умолчании, а не на данных.
"""
from __future__ import annotations

import re

# --- словари шаблона: первое значение столбца = умолчание -------------------------------
PROPS = ["блок", "ресивер", "осушитель", "частотник", "фильтры",
         "безмасляный", "охлаждение", "ступени", "двигатель", "передвижной"]
DEFAULTS = {"блок": "Baosi/Taitiang/OEM/BERG", "ресивер": "нет", "осушитель": "нет",
            "частотник": "нет", "фильтры": "нет", "безмасляный": "нет",
            "охлаждение": "воздушный", "ступени": "1", "двигатель": "асинхронный",
            "передвижной": "нет"}
# кВт, бар и IP в DEFAULTS сознательно нет — см. док-строку.

# Ряд мощностей шаблона. Нужен не для отсева (в каталогах есть 2,2 и 355 кВт), а чтобы
# отметить в отчёте строки вне ряда: заказчик анализирует в первую очередь этот ряд.
KW_LADDER = [4, 5.5, 7.5, 11, 15, 18.5, 22, 30, 37, 45, 55, 75, 90, 110, 132, 160, 185,
             200, 220, 250, 315]

# Классы винтового блока. Ключ — как в шаблоне, значение — что реально пишут на сайтах.
#
# Признаки разделены на точные и общие. Точный называет конкретную серию блока, общий —
# только производителя. Без этого деления «Hanbell AB (6 подшипников)» (699 карточек
# Enger на нашем сайте, 351 у Sollant) совпадал СРАЗУ с двумя классами — по «hanbell ab»
# и по голому «hanbell» — и отбрасывался как неоднозначный.
_BLOCK_EXACT = [
    ("Hanbell AB/SKK",          r"hanbell\s*ab|\bskk\b"),
    ("Hanbell AC/ Hanbell/ GE", r"hanbell\s*a[cс]"),
    ("Baosi/Taitiang/OEM/BERG", r"baosi|bao\s*si|tai\s*ti?an|taitiang|\boem\b|\bberg\b|\bберг\b"),
]
# Голый «Hanbell» — только когда за ним НЕ идёт код серии: иначе он снова перебивал бы
# точный признак. GE и GE Niemann отдельной серии не имеют, поэтому они всегда общие.
_BLOCK_LOOSE = [
    ("Hanbell AC/ Hanbell/ GE", r"hanbell(?!\s*a[abcсh])|ge\s*niemann|\bge\b"),
]

_IP_CLASS = {"23": "IP23", "54": "IP54/IP55", "55": "IP54/IP55", "65": "IP65"}

# Винтовой блок Enger по префиксу серии. Правило дал заказчик 25.08 и подтвердил
# карточкой 1С (HB-22DTRE-450 → «Hanbell AB (в подшипниках)»): в нашей выгрузке
# `specs_compact` свойства «Винтовой блок» нет вовсе, и все 2 701 винтовая карточка
# уезжала в умолчание шаблона «Baosi/Taitiang/OEM/BERG» — заказчик это и заметил.
#
# HA («Hanbell AA/AH») в шаблоне отдельной строкой не значится; отнесён к колонке с
# голым «Hanbell» — это ДОПУЩЕНИЕ, 58 карточек, требует подтверждения.
ENGER_BLOCK = {"HC": "Hanbell AC/ Hanbell/ GE",
               "HB": "Hanbell AB/SKK",
               "HA": "Hanbell AC/ Hanbell/ GE",
               "BS": "Baosi/Taitiang/OEM/BERG"}
_ENG_PREFIX = re.compile(r"\bEnger\s+([A-Z]{2})-", re.I)


# Охлаждение Enger по букве исполнения. Свойство «Тип охлаждения» (22669) заполнено в
# Битриксе у 1 325 карточек каталога и у НУЛЯ из Enger, поэтому вся колонка уходила в
# умолчание «воздушный» — включая 412 водяных машин, которые сравнивались с воздушными
# конкурентами (OFSZ-37W за 8 746 994 ₽ против EXO 37/10A за 3 460 795 ₽, разрыв 2,5x
# объясняется не ценой, а разными машинами).
#
# Улика, а не догадка: у 89 моделей на нашем же сайте лежат ОБА исполнения — LUF110A и
# LUF110W, LUF132A и LUF132W и так далее. Буква и есть охлаждение.
_ENG_COOL = re.compile(r"\d\s*([AW])\b")


def enger_cooling(name: str) -> str | None:
    """«LUF110W» → водяной, «LUF110A» → воздушный. None — буквы нет (масляные серии)."""
    m = _ENG_COOL.search(str(name or ""))
    return {"W": "водяной", "A": "воздушный"}.get(m.group(1)) if m else None


def enger_block(name: str) -> str | None:
    """Класс винтового блока по коду модели Enger. None — серия вне правила заказчика
    (LC, HJ, OFS, AHG и карточки без префикса: 1 017 из 2 701, блок остаётся неизвестным)."""
    m = _ENG_PREFIX.search(str(name or ""))
    return ENGER_BLOCK.get(m.group(1).upper()) if m else None


def ip_classes(text: str) -> frozenset | None:
    """Все классы защиты, названные в строке. «IP55, IP65» у GMP — это две модификации
    в одной карточке, а не одна: возвращаем множество, матчер сцепит по пересечению."""
    if not text:
        return None
    got = {_IP_CLASS[m] for m in re.findall(r"IP\s*[-–]?\s*(\d{2})", str(text), re.I)
           if m in _IP_CLASS}
    return frozenset(got) or None


def num(v) -> float | None:
    """Первое число из значения: «7,5 кВт» → 7.5, «500 лит» → 500."""
    if v is None:
        return None
    m = re.search(r"(\d+(?:[.,]\d+)?)", str(v).replace("\xa0", " "))
    return float(m.group(1).replace(",", ".")) if m else None


def bar_bucket(v) -> str | None:
    """Давление в терминах шаблона. Единственная склейка — «15/16»: в шаблоне это одна
    строка, значит 15 и 16 бар заказчик считает одним классом (у нас BS-…16, у BERG 15)."""
    x = num(v)
    if x is None or x <= 0:
        return None
    if 14.5 <= x <= 16.5:
        return "15/16"
    return str(int(x)) if abs(x - round(x)) < 0.05 else f"{x:g}"


# Ряд давлений шаблона. К нему приводится давление на ОТДЕЛЬНОМ листе отчёта: в основном
# сцепка строго по паспортному числу, как и просил заказчик («допусков нет»).
_BAR_LADDER = [7, 8, 10, 12, 13, 15.5, 20, 25, 30, 40]


def bar_classes(b: str | None) -> frozenset:
    """Классы ряда шаблона, к которым относится давление карточки.

    Зачем вообще: 323 наши строки не сцеплялись ни с чем только потому, что паспортное
    давление безмасляных серий (LUF 7,5 / 8,6 / 10,4 бар, OFSA 8,5) в ряду шаблона
    отсутствует, а у конкурентов те же машины стоят на 7/8/10. Порог 12% отобран по
    данным: 8,6→8 это 7,5%, 12,5→12 — 4%, а 3, 3,5, 35 и 70 бар остаются своим классом
    и ни к чему не подтягиваются.

    При равном расстоянии (7,5 бар — ровно между 7 и 8) возвращаем ОБА класса: выбирать
    за заказчика, куда отнести машину, оснований нет."""
    if b is None:
        return frozenset()
    if b == "15/16":
        return frozenset({"15/16"})
    try:
        x = float(b)
    except ValueError:
        return frozenset({b})
    best = min(abs(v - x) for v in _BAR_LADDER)
    near = [v for v in _BAR_LADDER if abs(v - x) <= best + 1e-9 and abs(v - x) <= 0.12 * max(v, x)]
    if not near:
        return frozenset({b})
    return frozenset("15/16" if v == 15.5 else str(int(v)) for v in near)


def kw_value(v) -> float | None:
    x = num(v)
    if x is None or not (0.5 <= x <= 1000):
        return None
    return round(x, 1)


# --- разбор словаря характеристик -------------------------------------------------------
_JUNK = re.compile(r"^(—|-|·|\.|нет данных|характеристики)$", re.I)


def pick(specs: dict, pattern: str, *, exclude: str = "") -> str | None:
    """Первое осмысленное значение по ключу, подходящему под regex.

    Значения на сайтах бывают мусорными: у crossair ключ «Модель винтового блока» несёт
    значение «Габариты, мм» (сдвиг колонок в таблице), у ironmac ключ и значение
    совпадают («ВИНТОВОЙ БЛОК BAOSI» → «ВИНТОВОЙ БЛОК BAOSI»). Такие пары молча
    пропускаем — лучше «не указано», чем ложное значение."""
    rx = re.compile(pattern, re.I)
    ex = re.compile(exclude, re.I) if exclude else None
    for k, v in specs.items():
        if not rx.search(k) or (ex and ex.search(k)):
            continue
        s = str(v).strip()
        if not s or _JUNK.match(s) or s.lower() == k.strip().lower() or len(s) > 60:
            continue
        return s
    return None


# «С преобразователем» — это единственное «да» у BERG (270 карточек, 33 модели), и без
# приставки «с …» оно уходило в умолчание «нет», хотя соседнее «Без преобразователя»
# ловилось. Требуем пробел после «с», чтобы не поймать «Стационарный».
_YES = re.compile(r"^\s*(да|есть|yes|\+|имеется|в комплекте|с\s+\w)", re.I)
_NO = re.compile(r"^\s*(нет|없|no|отсутств|без)", re.I)


def yesno(v) -> str | None:
    """да / нет / None. «без ресивера» у GMP — это «нет», а не «не указано»."""
    if v is None:
        return None
    s = str(v).strip()
    if not s:
        return None
    if _YES.match(s):
        return "да"
    if _NO.match(s):
        return "нет"
    return None


def yesno_or_model(v) -> str | None:
    """Как yesno, но конкретная модель узла = «да».

    У Comprag в «Осушитель рефрижераторный» стоит «RDX36», у GMP в «Модель осушителя» —
    «ADR-3,8», у ironmac в «Частотный преобразователь» — «Folinn». Это не мусор, это
    подтверждение наличия узла."""
    r = yesno(v)
    if r or v is None:
        return r
    s = str(v).strip()
    return "да" if re.search(r"[A-Za-zА-Яа-я]{2,}[- ]?\d|^\d+\s*(?:л|lit)", s) else None


# --- признаки из названия ---------------------------------------------------------------
# Ловим только однозначные маркеры. «D» у Ceccato = осушитель, но у Enger D = прямой
# привод — поэтому одиночные буквы разбираются в site-специфичных правилах, а не тут.
_N_OILFREE = re.compile(r"безмасл|oil[\s-]?free|\bof\b|сухого\s+сжатия|\bвбм\b|\bобм\b", re.I)
_N_TWOSTAGE = re.compile(r"двухступенчат|two[\s-]?stage|\bii\b(?!\w)", re.I)
_N_MOBILE = re.compile(r"передвижн|мобильн|на\s+шасси|прицеп|на\s+колёс|на\s+колес", re.I)
_N_PM = re.compile(r"постоянн\w*\s+магнит|\bpm\b|\bпм\b|permanent", re.I)
_N_WATER = re.compile(r"водян\w*\s+охлажд|водяного\s+охлажд|жидкостн\w*\s+охлажд|"
                      r"water[\s-]?cool", re.I)
_N_VSD = re.compile(r"частотн|\bvsd\b|\bvfd\b|\bчрп\b|инвертор", re.I)
_N_DRYER = re.compile(r"осушител|\bdry\b|\bdr\b(?!\w)", re.I)
_N_RECV = re.compile(r"ресивер|на\s+ресивере|\bресивере\b", re.I)


def from_name(name: str) -> dict:
    """Признаки, которые видны прямо в названии карточки. Возвращает только найденные —
    отсутствие маркера в имени НЕ означает «нет» (это решает вызывающая сторона)."""
    n = str(name or "")
    out = {}
    if _N_OILFREE.search(n):
        out["безмасляный"] = "да"
    if _N_TWOSTAGE.search(n):
        out["ступени"] = "2"
    if _N_MOBILE.search(n):
        out["передвижной"] = "да"
    if _N_PM.search(n):
        out["двигатель"] = "синхронный"
    if _N_WATER.search(n):
        out["охлаждение"] = "водяной"
    return out


def block_class(v) -> str | None:
    """Марка винтового блока → класс шаблона.

    «Hanbell AB (6 подшипников)» → «Hanbell AB/SKK»: точный признак перебивает общий.
    «HANBELL AB / GE» у GMP (536 карточек) → None: тут в одной карточке названы две
    РАЗНЫЕ серии, и выбрать за поставщика мы не можем.
    «Jiuyi», «HDHJ», «Ingersoll Rand», «ACI» → None: этих блоков в шаблоне нет вовсе."""
    if not v:
        return None
    s = str(v)
    exact = {name for name, pat in _BLOCK_EXACT if re.search(pat, s, re.I)}
    loose = {name for name, pat in _BLOCK_LOOSE if re.search(pat, s, re.I)}
    if len(exact) == 1 and not (loose - exact):
        return next(iter(exact))
    if not exact and len(loose) == 1:
        return next(iter(loose))
    return None


def motor_class(v) -> str | None:
    """«электрический асинхронный» → асинхронный, «на постоянных магнитах» → синхронный.

    Осторожно: у ironmac ключ «Тип двигателя» несёт «IP65» (у них это про защиту), у
    hansmann/zif — «Электрический»/«Дизельный» (это про род привода, не про тип обмотки).
    Такое возвращаем как None."""
    if not v:
        return None
    s = str(v).lower()
    # «асинхронный» проверяем ПЕРВЫМ: подстрока «синхрон» сидит внутри «аСИНХРОНный», и
    # обратный порядок выдавал синхронный двигатель у всей серии Exelute EXDM-RD, где в
    # карточке честно написано «Тип электродвигателя = Асинхронный».
    if "асинхрон" in s:
        return "асинхронный"
    if _N_PM.search(s) or "синхрон" in s:
        return "синхронный"
    return None


def cooling(v) -> str | None:
    if not v:
        return None
    s = str(v).lower()
    if "водян" in s or "жидкост" in s or "water" in s:
        return "водяной" if "воздуш" not in s else None   # «воздушная/водяная» = два исполнения
    if "воздуш" in s or "air" in s:
        return "воздушный"
    return None


def stages(v) -> str | None:
    x = num(v)
    if x is None:
        return None
    return str(int(x)) if 1 <= x <= 6 else None
